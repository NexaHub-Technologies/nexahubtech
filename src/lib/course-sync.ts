import type { Course } from "./courses";

/* The curriculum lives here, on the website. The staff dashboard (the
   nexahub-dash repo) keeps its own copy of each course's title, fee and
   modules, because cohorts, attendance and progress hang off them;
   scripts/sync-courses.ts brings that copy up to date. This module turns
   COURSES into the one SQL transaction that does it. */

export interface CourseRow {
	slug: string;
	title: string;
	feeKobo: number;
	modules: { n: number; title: string }[];
}

/* "₦160,000" → 16,000,000 kobo. Anything else stops the sync rather than
   recording a wrong fee. */
export function priceToKobo(price: string): number {
	const m = price.trim().match(/^₦(\d{1,3}(?:,\d{3})*)$/);
	if (!m) throw new Error(`can't read the price "${price}"`);
	return Number(m[1].replaceAll(",", "")) * 100;
}

export function toRows(courses: readonly Course[]): CourseRow[] {
	const slugs = new Set<string>();
	return courses.map((c) => {
		if (slugs.has(c.slug)) throw new Error(`course ${c.slug} appears twice`);
		slugs.add(c.slug);
		const seen = new Set<number>();
		const modules = c.modules.map((m) => {
			const n = Number(m.n);
			if (!Number.isInteger(n) || n < 1) {
				throw new Error(
					`${c.slug}: module number "${m.n}" isn't a positive whole number`,
				);
			}
			if (seen.has(n)) throw new Error(`${c.slug}: module ${n} appears twice`);
			seen.add(n);
			return { n, title: m.t };
		});
		return { slug: c.slug, title: c.t, feeKobo: priceToKobo(c.price), modules };
	});
}

/* a SQL string literal; standard_conforming_strings is on in every Postgres
   the dashboard uses, so doubling the quote is the whole job */
const lit = (s: string) => `'${s.replaceAll("'", "''")}'`;

/* One transaction: upsert every course and module, then remove modules the
   website no longer lists. Courses are never deleted (cohorts point at
   them). Module progress and sessions refer to a module by number only, so
   the transaction refuses to drop a module anything already refers to. */
export function syncSql(rows: readonly CourseRow[]): string {
	if (!rows.length) throw new Error("no courses to sync");
	const courses = rows
		.map((r) => `  (${lit(r.slug)}, ${lit(r.title)}, ${r.feeKobo})`)
		.join(",\n");
	const modules = rows
		.flatMap((r) =>
			r.modules.map((m) => `  (${lit(r.slug)}, ${m.n}, ${lit(m.title)})`),
		)
		.join(",\n");
	const kept = rows
		.flatMap((r) => r.modules.map((m) => `(${lit(r.slug)}, ${m.n})`))
		.join(", ");
	const synced = rows.map((r) => lit(r.slug)).join(", ");

	return `-- Generated by nexahubtech scripts/sync-courses.ts from src/lib/courses.ts.
begin;

create temporary table website_modules (course_slug text, n smallint) on commit drop;
insert into website_modules values ${kept};

do $$
declare v text;
begin
  select string_agg(distinct format('%s module %s', c.course_slug, p.module_n), ', ') into v
  from public.module_progress p
  join public.enrolments e on e.id = p.enrolment_id
  join public.cohorts c on c.id = e.cohort_id
  where c.course_slug in (${synced})
    and (c.course_slug, p.module_n) not in (select course_slug, n from website_modules);
  if v is not null then
    raise exception 'Not synced: progress is recorded against modules the website no longer lists (%)', v;
  end if;

  select string_agg(distinct format('%s module %s', c.course_slug, s.module_n), ', ') into v
  from public.sessions s
  join public.cohorts c on c.id = s.cohort_id
  where s.module_n is not null and c.course_slug in (${synced})
    and (c.course_slug, s.module_n) not in (select course_slug, n from website_modules);
  if v is not null then
    raise exception 'Not synced: sessions are scheduled for modules the website no longer lists (%)', v;
  end if;
end $$;

insert into public.courses (slug, title, default_fee_kobo) values
${courses}
on conflict (slug) do update
  set title = excluded.title, default_fee_kobo = excluded.default_fee_kobo, updated_at = now()
  where (courses.title, courses.default_fee_kobo) is distinct from (excluded.title, excluded.default_fee_kobo);

insert into public.course_modules (course_slug, n, title) values
${modules}
on conflict (course_slug, n) do update
  set title = excluded.title
  where course_modules.title is distinct from excluded.title;

delete from public.course_modules m
where m.course_slug in (${synced})
  and (m.course_slug, m.n) not in (select course_slug, n from website_modules);

commit;
`;
}
