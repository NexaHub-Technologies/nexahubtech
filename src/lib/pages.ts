export function coursePage(course: Course): Page {
	return {
		path: `/courses/${course.slug}`,
		name: course.t,
		title: `${course.t} — NexaHubTech`,
		description: course.tagline,
		image: `/og/course-${course.slug}.jpg`,
		kind: "WebPage",
	};
}

