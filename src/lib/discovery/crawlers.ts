export const ALLOW_TRAINING = true;

/* Server-function RPC endpoints (TanStack Start's default base). They answer
   POSTs from the enquiry and enrolment forms; there is nothing to read there. */
const DISALLOW = ["/_serverFn/"];

const PURPOSE_HEADINGS: Record<CrawlerPurpose, string> = {
	search: "AI search engines — fetch pages to cite them in answers",
	user: "AI assistants — fetch a page because a person asked about it",
	training: "AI model training",
};

/* A crawler that finds a group naming it ignores the * group entirely, so every
   group repeats the disallow rules rather than inheriting them. */
function group(agents: string[], allow: boolean): string {
	const rules = allow
		? ["Allow: /", ...DISALLOW.map((p) => `Disallow: ${p}`)]
		: ["Disallow: /"];
	return [...agents.map((a) => `User-agent: ${a}`), ...rules].join("\n");
}

export function robotsTxt(): string {
	const purposes: CrawlerPurpose[] = ["search", "user", "training"];
	const named = purposes.map((purpose) => {
		const crawlers = AI_CRAWLERS.filter((c) => c.purpose === purpose);
		const allow = purpose !== "training" || ALLOW_TRAINING;
		return `# ${PURPOSE_HEADINGS[purpose]}
# ${crawlers.map((c) => `${c.agent} (${c.operator})`).join(", ")}
${group(
	crawlers.map((c) => c.agent),
	allow,
)}`;
	});

	return `# NexaHubTech crawler policy.
# Generated by scripts/generate-discovery.ts from src/lib/discovery/ — edit there.
#
# Every page renders in the browser, so a crawler that does not run JavaScript
# should read the markdown versions instead:
#   ${SITE_URL}/llms.txt        index of every page, as markdown
#   ${SITE_URL}/llms-full.txt   the whole site in one file
#   ${SITE_URL}/schema.json     schema.org knowledge graph
#
# Hidden pages are kept out of search with a noindex tag, not a Disallow here:
# a disallowed URL can still be indexed from a link elsewhere, because the
# crawler is never allowed to fetch the page and see the instruction.

${group(["*"], true)}
Content-Signal: search=yes, ai-input=yes, ai-train=${ALLOW_TRAINING ? "yes" : "no"}

${named.join("\n\n")}

Sitemap: ${SITE_URL}/sitemap.xml
`;
}

/* No <lastmod>: every URL used to carry the date the generator last ran, which
   told search engines that all of them changed on that day. A date that is not
   true is worse than none, and nothing here records when a page last changed. */
export function sitemapXml(): string {
	return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${INDEXABLE_PAGES.map((p) => `  <url>\n    <loc>${SITE_URL}${p.path}</loc>\n  </url>`).join("\n")}
</urlset>
`;
}
