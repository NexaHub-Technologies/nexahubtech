/* robots.txt and sitemap.xml, built from the page registry.

   The crawler policy is a decision, not a default, so every AI crawler that
   matters is named with what it is for. The site wants to be found and quoted:
   a small school and studio gains far more from being the answer an assistant
   gives than it loses by being read. To withdraw from model training while
   staying citable in AI answers, set ALLOW_TRAINING to false — the search and
   user-fetch agents are kept separate precisely so that is a one-line change. */

import { SITE_URL } from "../contact";
import { INDEXABLE_PAGES } from "../pages";

export type CrawlerPurpose =
	/* fetches pages to cite them in AI search results */
	| "search"
	/* fetches a page because a person asked an assistant about it */
	| "user"
	/* collects pages to train models */
	| "training";

export interface Crawler {
	agent: string;
	operator: string;
	purpose: CrawlerPurpose;
}

